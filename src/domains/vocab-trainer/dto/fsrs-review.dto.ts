import { ApiProperty } from '@nestjs/swagger';
import { FsrsRating, QuestionType } from '@prisma/client';
import { Type } from 'class-transformer';
import { IsDate, IsEnum, IsIn, IsInt, IsNotEmpty, IsNumber, IsOptional, IsString, Max, MaxLength, Min } from 'class-validator';
import { FSRS_MAX_DESIRED_RETENTION, FSRS_MAX_INTERVAL_DAYS, FSRS_MIN_DESIRED_RETENTION } from '../utils/fsrs-trainer-rules';

const MAX_DURATION_MS = 60 * 60 * 1000;
const MAX_AHEAD_DAYS = 365;
const MAX_SESSION_LIMIT = 100;
const MAX_ANSWER_LENGTH = 500;

export class FsrsReviewQueueQueryInput {
    @ApiProperty({ description: 'Max cards in the session (due first, then new)', required: false, minimum: 1, maximum: MAX_SESSION_LIMIT, default: 20 })
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(1)
    @Max(MAX_SESSION_LIMIT)
    public limit?: number;

    @ApiProperty({ description: 'Also include cards due within this many days after today', required: false, minimum: 0, maximum: MAX_AHEAD_DAYS, default: 0 })
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(0)
    @Max(MAX_AHEAD_DAYS)
    public ahead?: number;
}

export class FsrsReviewAnswerInput {
    @ApiProperty({ description: 'The card that was answered' })
    @IsString()
    @IsNotEmpty()
    public cardId: string;

    @ApiProperty({ description: 'Generated by the client for each answer; sending the same one again does not schedule twice' })
    @IsString()
    @IsNotEmpty()
    @MaxLength(100)
    public answerId: string;

    @ApiProperty({ description: 'The button the user pressed', enum: FsrsRating })
    @IsEnum(FsrsRating)
    public rating: FsrsRating;

    @ApiProperty({ description: 'How the card was answered', enum: [QuestionType.FLIP_CARD, QuestionType.FILL_IN_THE_BLANK] })
    @IsIn([QuestionType.FLIP_CARD, QuestionType.FILL_IN_THE_BLANK])
    public questionType: QuestionType;

    @ApiProperty({ description: 'Time from showing the card to rating it, in ms', required: false })
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(0)
    @Max(MAX_DURATION_MS)
    public durationMs?: number;
}

export class FsrsReviewCheckInput {
    @ApiProperty({ description: 'The card that is being answered' })
    @IsString()
    @IsNotEmpty()
    public cardId: string;

    @ApiProperty({ description: 'What the user typed' })
    @IsString()
    @MaxLength(MAX_ANSWER_LENGTH)
    public answer: string;
}

/** Settings of an FSRS trainer that can change after creation. Names are unprefixed: they map to the `fsrs*` columns. */
export class UpdateFsrsSettingsInput {
    @ApiProperty({ description: 'Target recall probability at review time', required: false, minimum: FSRS_MIN_DESIRED_RETENTION, maximum: FSRS_MAX_DESIRED_RETENTION })
    @IsOptional()
    @Type(() => Number)
    @IsNumber()
    @Min(FSRS_MIN_DESIRED_RETENTION)
    @Max(FSRS_MAX_DESIRED_RETENTION)
    public desiredRetention?: number;

    @ApiProperty({ description: 'Longest gap between reviews, in days', required: false, minimum: 1, maximum: FSRS_MAX_INTERVAL_DAYS })
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(1)
    @Max(FSRS_MAX_INTERVAL_DAYS)
    public maximumInterval?: number;

    @ApiProperty({ description: 'Max new words per day; null = unlimited', required: false, nullable: true, minimum: 1 })
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(1)
    public newPerDay?: number | null;

    @ApiProperty({ description: 'End of the cycle, must be in the future; null = no end', required: false, nullable: true })
    @IsOptional()
    @Type(() => Date)
    @IsDate()
    public endsAt?: Date | null;

    // Declared only so that sending them is answered with a clear 400 instead of being ignored: both are fixed at creation.
    @IsOptional()
    public mode?: unknown;

    @IsOptional()
    public directions?: unknown;
}
